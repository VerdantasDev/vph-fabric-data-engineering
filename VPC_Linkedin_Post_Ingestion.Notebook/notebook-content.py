import pandas as pd
from pyspark.sql import SparkSession
from pyspark.sql.functions import current_date

# METADATA ********************

# META {
# META   "language": "python",
# META   "language_group": "synapse_pyspark"
# META }

# CELL ********************

# Initialize Spark Session
spark = SparkSession.builder \
    .appName("JoinLakehouseTables") \
    .getOrCreate()

# Define paths to your Lakehouse tables
lakehouse_path = "Tables"
table_paths = {
    "postContent": f"{lakehouse_path}/br_linkedin_post_content",
    "postEngagements": f"{lakehouse_path}/br_linkedin_post_engagements"
    }
# Read tables into DataFrames
df_content = spark.read.format("delta").load(table_paths["postContent"])
df_engagements = spark.read.format("delta").load(table_paths["postEngagements"])

# METADATA ********************

# META {
# META   "language": "python",
# META   "language_group": "synapse_pyspark"
# META }

# CELL ********************

joined_df = df_content.join(df_engagements, on='postID', how='left')

# METADATA ********************

# META {
# META   "language": "python",
# META   "language_group": "synapse_pyspark"
# META }

# CELL ********************

joined_df = joined_df.drop("dateMeasured")

# METADATA ********************

# META {
# META   "language": "python",
# META   "language_group": "synapse_pyspark"
# META }

# CELL ********************

joined_df = joined_df.withColumn("dateMeasured", current_date())

# METADATA ********************

# META {
# META   "language": "python",
# META   "language_group": "synapse_pyspark"
# META }

# CELL ********************

delta_table_path = "Tables/sv_linkedin_post_data"

# Write the DataFrame to Delta Lake
joined_df.write.format("delta").mode("overwrite").save(delta_table_path)

